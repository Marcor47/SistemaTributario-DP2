-- Refinamiento según el Catálogo de Requisitos v11 y el Backlog v1 (24/10/2026):
--   1. RF-014: etapas de la cobranza inductiva (mora temprana, campañas, valores emitidos, espera legal) y la
--      etapa informativa final, exigible en la vía coactiva (respuesta de la Municipalidad del 24/10).
--   2. RF-034: la Constancia de No Adeudo la gestiona un operador (verifica la deuda, emite la orden de pago
--      y, tras el pago, envía la constancia al buzón); la firma de la Municipalidad sigue siendo automática.
--   3. RF-064 / HU050: reclamos de contribuyentes y de trabajadores internos, con su historial de derivaciones
--      y el rol Gestor de reclamos.

-- ===== 1. Etapas de la cobranza inductiva (RF-014) =====
-- La notificación del valor abre la espera legal (20 días hábiles para pagar o reclamar). Si vence sin pago ni
-- reclamación, la deuda es exigible en la vía coactiva: el sistema solo informa esa etapa; el procedimiento
-- coactivo sigue fuera del alcance.
ALTER TABLE samnet.seguimiento_cobranza DROP CONSTRAINT seguimiento_cobranza_etapa_check;
UPDATE samnet.seguimiento_cobranza SET etapa = 'MORA_TEMPRANA' WHERE etapa = 'ORDINARIA';
UPDATE samnet.seguimiento_cobranza SET etapa = 'ESPERA_LEGAL' WHERE etapa = 'VALOR_NOTIFICADO';
ALTER TABLE samnet.seguimiento_cobranza
    ADD CONSTRAINT ck_seguimiento_cobranza_etapa
        CHECK (etapa IN ('MORA_TEMPRANA', 'CAMPANA', 'VALOR_EMITIDO', 'ESPERA_LEGAL', 'COACTIVA'));

-- ===== 2. Constancia de No Adeudo gestionada por un operador (RF-034, RF-055) =====
-- Secuencia: INICIADA → FIRMADA (contribuyente, en la app) → DEUDA_VERIFICADA (operador) →
-- ORDEN_PAGO_EMITIDA (operador) → PAGADA → EMITIDA (operador; firma municipal automática). En ventanilla
-- no hay firma del contribuyente y el trabajador actúa como operador.
ALTER TABLE operativo.solicitud_constancia DROP CONSTRAINT solicitud_constancia_estado_check;
ALTER TABLE operativo.solicitud_constancia
    ADD CONSTRAINT ck_solicitud_constancia_estado CHECK (estado IN
        ('INICIADA', 'FIRMADA', 'DEUDA_VERIFICADA', 'ORDEN_PAGO_EMITIDA', 'PAGADA', 'EMITIDA', 'RECHAZADA')),
    ADD COLUMN id_operador    BIGINT REFERENCES seguridad.usuario (id_usuario),
    ADD COLUMN fecha_revision TIMESTAMP,
    ADD CONSTRAINT ck_solicitud_constancia_operador
        CHECK (estado IN ('INICIADA', 'FIRMADA') OR (id_operador IS NOT NULL AND fecha_revision IS NOT NULL));

-- Número de constancia asignado por el sistema (RF-055): CNA-AAAA-NNNNNN.
CREATE SEQUENCE operativo.seq_numero_constancia;

CREATE FUNCTION operativo.fn_siguiente_numero_constancia(p_fecha DATE) RETURNS VARCHAR
LANGUAGE sql VOLATILE AS $$
    SELECT 'CNA-' || to_char(p_fecha, 'YYYY') || '-'
           || lpad(nextval('operativo.seq_numero_constancia')::TEXT, 6, '0');
$$;


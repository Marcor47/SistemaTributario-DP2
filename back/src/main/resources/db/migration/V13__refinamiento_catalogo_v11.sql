-- Áreas de la Municipalidad a las que se derivan los reclamos.
CREATE TABLE operativo.area_municipal (
    id_area BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(30)  NOT NULL UNIQUE,
    nombre  VARCHAR(120) NOT NULL,
    activa  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE SEQUENCE operativo.seq_numero_reclamo;

CREATE FUNCTION operativo.fn_siguiente_numero_reclamo(p_fecha DATE) RETURNS VARCHAR
LANGUAGE sql VOLATILE AS $$
    SELECT 'REC-' || to_char(p_fecha, 'YYYY') || '-'
           || lpad(nextval('operativo.seq_numero_reclamo')::TEXT, 6, '0');
$$;

-- Un mismo formulario para contribuyentes (app móvil) y trabajadores internos (plataforma web); solo cambian
-- los tipos de reclamo permitidos según quién reclama.
CREATE TABLE operativo.reclamo (
    id_reclamo              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_reclamo          VARCHAR(20)  NOT NULL UNIQUE,
    tipo_reclamante         VARCHAR(15)  NOT NULL CHECK (tipo_reclamante IN ('CONTRIBUYENTE', 'TRABAJADOR')),
    -- Reclamo de un contribuyente: su DNI o RUC. Reclamo de un trabajador: su usuario interno.
    documento_contribuyente VARCHAR(12),
    id_usuario_reclamante   BIGINT       REFERENCES seguridad.usuario (id_usuario),
    tipo_reclamo            VARCHAR(20)  NOT NULL CHECK (tipo_reclamo IN
                                ('COBRANZA', 'SERVICIO', 'ATENCION', 'AREA_RELACIONADA', 'DOCUMENTO', 'OTRO')),
    -- Documento o servicio al que se refiere (número de valor, constancia, trámite, pantalla de la app, etc.).
    referencia              VARCHAR(150),
    fecha_hora_incidente    TIMESTAMP    NOT NULL,
    comentario              TEXT         NOT NULL CHECK (length(comentario) BETWEEN 1 AND 2000),
    estado                  VARCHAR(25)  NOT NULL CHECK (estado IN
                                ('ENVIADO', 'EN_REVISION', 'APROBADO_CON_RESPUESTA', 'CANCELADO')),
    fecha_registro          TIMESTAMP    NOT NULL,
    -- Área y encargado de revisión actuales (la última derivación).
    id_area_actual          BIGINT       REFERENCES operativo.area_municipal (id_area),
    id_responsable_actual   BIGINT       REFERENCES seguridad.usuario (id_usuario),
    respuesta               TEXT,
    fecha_respuesta         TIMESTAMP,
    CONSTRAINT ck_reclamo_reclamante CHECK (
        (tipo_reclamante = 'CONTRIBUYENTE' AND documento_contribuyente IS NOT NULL AND id_usuario_reclamante IS NULL)
        OR (tipo_reclamante = 'TRABAJADOR' AND id_usuario_reclamante IS NOT NULL AND documento_contribuyente IS NULL)),
    CONSTRAINT ck_reclamo_tipo_por_reclamante CHECK (
        (tipo_reclamante = 'CONTRIBUYENTE' AND tipo_reclamo IN ('COBRANZA', 'SERVICIO', 'ATENCION', 'OTRO'))
        OR (tipo_reclamante = 'TRABAJADOR' AND tipo_reclamo IN ('AREA_RELACIONADA', 'DOCUMENTO', 'COBRANZA', 'OTRO'))),
    CONSTRAINT ck_reclamo_incidente CHECK (fecha_hora_incidente <= fecha_registro),
    CONSTRAINT ck_reclamo_respuesta CHECK (estado <> 'APROBADO_CON_RESPUESTA'
                                           OR (respuesta IS NOT NULL AND fecha_respuesta IS NOT NULL)),
    CONSTRAINT ck_reclamo_en_revision CHECK (estado <> 'EN_REVISION'
                                             OR (id_area_actual IS NOT NULL AND id_responsable_actual IS NOT NULL))
);

CREATE INDEX ix_reclamo_estado ON operativo.reclamo (estado, fecha_registro);
CREATE INDEX ix_reclamo_documento ON operativo.reclamo (documento_contribuyente);
CREATE INDEX ix_reclamo_usuario_reclamante ON operativo.reclamo (id_usuario_reclamante);
CREATE INDEX ix_reclamo_responsable ON operativo.reclamo (id_responsable_actual);
CREATE INDEX ix_reclamo_area ON operativo.reclamo (id_area_actual);

-- Registro de derivaciones de encargado de revisión por reclamo; solo se inserta.
CREATE TABLE operativo.derivacion_reclamo (
    id_derivacion    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reclamo       BIGINT       NOT NULL REFERENCES operativo.reclamo (id_reclamo),
    id_area_destino  BIGINT       NOT NULL REFERENCES operativo.area_municipal (id_area),
    -- Encargado de revisión en el área destino.
    id_responsable   BIGINT       NOT NULL REFERENCES seguridad.usuario (id_usuario),
    -- Gestor de reclamos que deriva.
    id_derivado_por  BIGINT       NOT NULL REFERENCES seguridad.usuario (id_usuario),
    fecha_derivacion TIMESTAMP    NOT NULL,
    observacion      VARCHAR(400)
);

CREATE INDEX ix_derivacion_reclamo ON operativo.derivacion_reclamo (id_reclamo, fecha_derivacion);
CREATE INDEX ix_derivacion_area ON operativo.derivacion_reclamo (id_area_destino);
CREATE INDEX ix_derivacion_responsable ON operativo.derivacion_reclamo (id_responsable);
CREATE INDEX ix_derivacion_derivado_por ON operativo.derivacion_reclamo (id_derivado_por);

CREATE TRIGGER tg_derivacion_reclamo_inalterable
    BEFORE UPDATE OR DELETE ON operativo.derivacion_reclamo
    FOR EACH ROW EXECUTE FUNCTION seguridad.fn_registro_inalterable();

-- La respuesta a un reclamo de contribuyente llega a su buzón ("actúa como buzonería").
ALTER TABLE operativo.documento_buzon DROP CONSTRAINT documento_buzon_tipo_check;
ALTER TABLE operativo.documento_buzon
    ADD CONSTRAINT ck_documento_buzon_tipo CHECK (tipo IN
        ('CONSTANCIA', 'ESTADO_CUENTA', 'RESPUESTA_SOLICITUD', 'RESPUESTA_RECLAMO')),
    ADD COLUMN id_reclamo BIGINT UNIQUE REFERENCES operativo.reclamo (id_reclamo);

-- Modelo estrella (analítica) y seguimiento institucional: indicadores, metas, valores y alertas.
-- La analítica no guarda DNI, RUC, nombres ni correos en texto plano: solo seudónimos (RNF-018).

-- ===== Modelo estrella =====

CREATE TABLE analitica.dim_contribuyente (
    seudonimo_contribuyente  VARCHAR(64)   PRIMARY KEY,
    tipo_persona             VARCHAR(10)   NOT NULL CHECK (tipo_persona IN ('NATURAL', 'JURIDICA')),
    regimen                  VARCHAR(40),
    condicion                VARCHAR(40),
    -- Regularidad de pago del año (RF-011).
    porcentaje_pago_a_tiempo NUMERIC(5, 2) CHECK (porcentaje_pago_a_tiempo BETWEEN 0 AND 100),
    -- Segmento actual de la Municipalidad: puntual, vecino excelente, moroso recurrente u otro.
    segmento_binario_actual  VARCHAR(30)
);

CREATE TABLE analitica.dim_predio (
    id_predio       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seudonimo_predio VARCHAR(64)    NOT NULL UNIQUE,
    zona            VARCHAR(20)    NOT NULL,
    uso_predio      VARCHAR(60),
    tipo_predio     VARCHAR(10)    NOT NULL CHECK (tipo_predio IN ('URBANO', 'RUSTICO', 'OTRO')),
    base_imponible  NUMERIC(14, 2) CHECK (base_imponible >= 0)
);

CREATE INDEX ix_dim_predio_zona ON analitica.dim_predio (zona);

-- Hecho por cuota de cada tributo (RF-009, RF-012, RF-024, RF-050).
CREATE TABLE analitica.hecho_cobranza (
    id_hecho                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote                 BIGINT         NOT NULL REFERENCES analitica.lote_etl (id_lote),
    seudonimo_contribuyente VARCHAR(64)    NOT NULL REFERENCES analitica.dim_contribuyente (seudonimo_contribuyente),
    id_predio               BIGINT         NOT NULL REFERENCES analitica.dim_predio (id_predio),
    tributo                 VARCHAR(25)    NOT NULL CHECK (tributo IN
                                ('IMPUESTO_PREDIAL', 'LIMPIEZA_PUBLICA', 'PARQUES_JARDINES', 'SEGURIDAD_CIUDADANA')),
    anio                    INTEGER        NOT NULL,
    cuota                   INTEGER        NOT NULL CHECK (cuota BETWEEN 1 AND 12),
    fecha_vencimiento       DATE           NOT NULL,
    monto_emitido           NUMERIC(14, 2) NOT NULL CHECK (monto_emitido >= 0),
    monto_insoluto          NUMERIC(14, 2) NOT NULL CHECK (monto_insoluto >= 0),
    monto_pagado            NUMERIC(14, 2) NOT NULL CHECK (monto_pagado >= 0),
    monto_descuento         NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (monto_descuento >= 0),
    estado_pago             VARCHAR(10)    NOT NULL CHECK (estado_pago IN ('PENDIENTE', 'PAGADA', 'VENCIDA'))
);

CREATE INDEX ix_hecho_cobranza_lote ON analitica.hecho_cobranza (id_lote);
CREATE INDEX ix_hecho_cobranza_periodo ON analitica.hecho_cobranza (anio, cuota, tributo);
CREATE INDEX ix_hecho_cobranza_contribuyente ON analitica.hecho_cobranza (seudonimo_contribuyente);

-- Hecho por pago (RF-051, RF-062).
CREATE TABLE analitica.hecho_pago (
    id_hecho_pago           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote                 BIGINT         NOT NULL REFERENCES analitica.lote_etl (id_lote),
    seudonimo_contribuyente VARCHAR(64)    NOT NULL REFERENCES analitica.dim_contribuyente (seudonimo_contribuyente),
    fecha_pago              DATE           NOT NULL,
    canal                   VARCHAR(10)    NOT NULL CHECK (canal IN ('VENTANILLA', 'EN_LINEA')),
    monto_pagado            NUMERIC(14, 2) NOT NULL CHECK (monto_pagado > 0),
    beneficio_aplicado      VARCHAR(20),
    monto_correspondiente   NUMERIC(14, 2) NOT NULL CHECK (monto_correspondiente >= 0)
);

CREATE INDEX ix_hecho_pago_lote ON analitica.hecho_pago (id_lote);
CREATE INDEX ix_hecho_pago_contribuyente ON analitica.hecho_pago (seudonimo_contribuyente, fecha_pago);

-- ===== Seguimiento institucional =====

-- Meta: se agregan alcance, umbral de desvío y usuario que la registró (RF-010, RF-052).
-- Las metas existentes quedan con alcance TOTAL y el umbral por defecto.
ALTER TABLE analitica.meta_indicador
    ADD COLUMN alcance             VARCHAR(10)   NOT NULL DEFAULT 'TOTAL'
        CHECK (alcance IN ('TOTAL', 'TRIBUTO', 'ZONA', 'SEGMENTO')),
    ADD COLUMN valor_alcance       VARCHAR(40),
    ADD COLUMN umbral_desvio       NUMERIC(5, 2) NOT NULL DEFAULT 10 CHECK (umbral_desvio BETWEEN 0 AND 100),
    ADD COLUMN id_usuario_registro BIGINT        REFERENCES seguridad.usuario (id_usuario),
    ADD CONSTRAINT ck_meta_valor_alcance CHECK ((alcance = 'TOTAL') = (valor_alcance IS NULL));

-- Valor de un indicador calculado en una carga del ETL (RF-009, RF-012).
CREATE TABLE analitica.valor_indicador (
    id_valor         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicador_codigo VARCHAR(40)    NOT NULL REFERENCES analitica.indicador (codigo),
    id_lote          BIGINT         NOT NULL REFERENCES analitica.lote_etl (id_lote),
    anio             INTEGER        NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    numero_periodo   INTEGER        NOT NULL CHECK (numero_periodo BETWEEN 1 AND 12),
    alcance          VARCHAR(10)    NOT NULL CHECK (alcance IN ('TOTAL', 'TRIBUTO', 'ZONA', 'SEGMENTO')),
    valor_alcance    VARCHAR(40),
    valor            NUMERIC(14, 4) NOT NULL,
    fecha_corte      DATE           NOT NULL,
    CONSTRAINT ck_valor_alcance CHECK ((alcance = 'TOTAL') = (valor_alcance IS NULL)),
    CONSTRAINT uq_valor_indicador UNIQUE NULLS NOT DISTINCT
        (indicador_codigo, id_lote, anio, numero_periodo, alcance, valor_alcance)
);

CREATE INDEX ix_valor_indicador_periodo ON analitica.valor_indicador (indicador_codigo, anio, numero_periodo);

-- Alerta del dashboard cuando una carga deja un indicador fuera del umbral de su meta (RF-052).
CREATE TABLE analitica.alerta_desvio (
    id_alerta         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Meta 1 genera * AlertaDesvio; ValorIndicador 1 origina * AlertaDesvio
    id_meta           BIGINT         NOT NULL REFERENCES analitica.meta_indicador (id),
    id_valor          BIGINT         NOT NULL REFERENCES analitica.valor_indicador (id_valor),
    valor_observado   NUMERIC(14, 4) NOT NULL,
    valor_meta        NUMERIC(14, 2) NOT NULL,
    desvio_porcentual NUMERIC(7, 2)  NOT NULL,
    fecha_generacion  TIMESTAMP      NOT NULL,
    activa            BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE INDEX ix_alerta_desvio_activa ON analitica.alerta_desvio (activa, fecha_generacion DESC);

-- Esquema operativo: plantillas, buzón y avisos; Constancia de No Adeudo y pago en línea; registro y
-- traspaso de predio; copia del estado de cuenta; configuración y uso de reportes.
-- Las referencias a SAMNET (contribuyente, predio, obligación) se guardan como claves sin FK.

-- ===== Documentos, buzón y avisos =====

-- Maestro de formularios y plantillas oficiales (RF-063, RF-046).
CREATE TABLE operativo.plantilla_documento (
    id_plantilla BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Código estable que usa la API de formularios (p. ej. FORM_DJ_PREDIAL).
    codigo       VARCHAR(80)  NOT NULL UNIQUE,
    nombre       VARCHAR(200) NOT NULL,
    tipo         VARCHAR(20)  NOT NULL CHECK (tipo IN ('DOCUMENTO_GENERADO', 'FORMULARIO_MANUAL')),
    descripcion  VARCHAR(400)
);

-- PlantillaDocumento 1 ◆ 1..* VersionPlantilla; solo una vigente por plantilla.
CREATE TABLE operativo.version_plantilla (
    id_version        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_plantilla      BIGINT       NOT NULL REFERENCES operativo.plantilla_documento (id_plantilla),
    numero_version    INTEGER      NOT NULL CHECK (numero_version >= 1),
    -- Nombre del archivo publicado.
    archivo           VARCHAR(255) NOT NULL,
    fecha_publicacion TIMESTAMP WITH TIME ZONE NOT NULL,
    vigente           BOOLEAN      NOT NULL,
    id_publicador     BIGINT       REFERENCES seguridad.usuario (id_usuario),
    -- Almacenamiento del archivo (detalle físico heredado de HU049).
    tipo_contenido    VARCHAR(120) NOT NULL,
    contenido         BYTEA        NOT NULL,
    CONSTRAINT uq_version_plantilla UNIQUE (id_plantilla, numero_version)
);

CREATE UNIQUE INDEX uq_version_plantilla_vigente
    ON operativo.version_plantilla (id_plantilla) WHERE vigente;

-- Se trasladan los formularios publicados con HU049 y se retira la tabla anterior.
INSERT INTO operativo.plantilla_documento (codigo, nombre, tipo)
SELECT DISTINCT ON (f.codigo) f.codigo, f.nombre, 'FORMULARIO_MANUAL'
FROM public.formulario_version f
ORDER BY f.codigo, f.version_numero DESC;

INSERT INTO operativo.version_plantilla
    (id_plantilla, numero_version, archivo, fecha_publicacion, vigente, tipo_contenido, contenido)
SELECT p.id_plantilla, f.version_numero, f.nombre_archivo, f.fecha_publicacion, f.vigente, f.tipo_contenido,
       f.contenido
FROM public.formulario_version f
JOIN operativo.plantilla_documento p ON p.codigo = f.codigo;

DROP TABLE public.formulario_version;

-- ===== Constancia de No Adeudo y pago en línea =====

-- El servidor controla la secuencia deuda 0 → firma → pago → emisión (RNF-029).
CREATE TABLE operativo.solicitud_constancia (
    id_solicitud             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal                    VARCHAR(10)  NOT NULL CHECK (canal IN ('APP', 'VENTANILLA')),
    estado                   VARCHAR(20)  NOT NULL CHECK (estado IN
                                 ('INICIADA', 'DEUDA_VERIFICADA', 'FIRMADA', 'PAGADA', 'EMITIDA', 'RECHAZADA')),
    fecha_solicitud          TIMESTAMP    NOT NULL,
    documento_contribuyente  VARCHAR(12)  NOT NULL,
    motivo_rechazo           VARCHAR(400),
    id_trabajador            BIGINT       REFERENCES seguridad.usuario (id_usuario),
    CONSTRAINT ck_solicitud_constancia_ventanilla CHECK (canal = 'APP' OR id_trabajador IS NOT NULL),
    CONSTRAINT ck_solicitud_constancia_rechazo CHECK (estado <> 'RECHAZADA' OR motivo_rechazo IS NOT NULL)
);

CREATE INDEX ix_solicitud_constancia_documento ON operativo.solicitud_constancia (documento_contribuyente);

-- SolicitudConstancia 1 ◆ 0..2 FirmaDigital (una del contribuyente y otra de la Municipalidad).
CREATE TABLE operativo.firma_digital (
    id_firma               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud           BIGINT       NOT NULL REFERENCES operativo.solicitud_constancia (id_solicitud)
                                            ON DELETE CASCADE,
    tipo_firmante          VARCHAR(15)  NOT NULL CHECK (tipo_firmante IN ('CONTRIBUYENTE', 'MUNICIPALIDAD')),
    entidad_certificadora  VARCHAR(120) NOT NULL,
    fecha_firma            TIMESTAMP    NOT NULL,
    valida                 BOOLEAN      NOT NULL,
    hash_documento         VARCHAR(64)  NOT NULL,
    CONSTRAINT uq_firma_por_firmante UNIQUE (id_solicitud, tipo_firmante)
);

-- Intento de pago con Niubiz; no almacena datos de tarjeta (RNF-011).
CREATE TABLE operativo.transaccion_pago (
    id_transaccion          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_contribuyente VARCHAR(12)    NOT NULL,
    motivo                  VARCHAR(20)    NOT NULL CHECK (motivo IN ('OBLIGACIONES', 'DERECHO_TRAMITE')),
    monto_base              NUMERIC(14, 2) NOT NULL CHECK (monto_base >= 0),
    monto_descuento         NUMERIC(14, 2) NOT NULL DEFAULT 0 CHECK (monto_descuento >= 0),
    monto_total             NUMERIC(14, 2) NOT NULL CHECK (monto_total > 0),
    estado                  VARCHAR(10)    NOT NULL CHECK (estado IN ('INICIADA', 'CONFIRMADA', 'RECHAZADA', 'EXPIRADA')),
    id_orden_pasarela       VARCHAR(40)    UNIQUE,
    fecha_hora              TIMESTAMP      NOT NULL,
    comprobante             VARCHAR(60),
    -- SolicitudConstancia 1 cobra trámite 0..1 TransaccionPago
    id_solicitud_constancia BIGINT         UNIQUE REFERENCES operativo.solicitud_constancia (id_solicitud),
    CONSTRAINT ck_transaccion_monto CHECK (monto_total = monto_base - monto_descuento),
    CONSTRAINT ck_transaccion_tramite CHECK ((motivo = 'DERECHO_TRAMITE') = (id_solicitud_constancia IS NOT NULL))
);

-- TransaccionPago * paga * Obligacion (obligación de SAMNET).
CREATE TABLE operativo.transaccion_obligacion (
    id_transaccion BIGINT      NOT NULL REFERENCES operativo.transaccion_pago (id_transaccion) ON DELETE CASCADE,
    id_obligacion  VARCHAR(20) NOT NULL,
    PRIMARY KEY (id_transaccion, id_obligacion)
);

-- Constancia emitida con el formato oficial y la firma de la Municipalidad (RF-037, RF-046, RF-055).
CREATE TABLE operativo.constancia (
    numero_constancia     VARCHAR(20)  PRIMARY KEY,
    -- SolicitudConstancia 1 emite 0..1 Constancia
    id_solicitud          BIGINT       NOT NULL UNIQUE REFERENCES operativo.solicitud_constancia (id_solicitud),
    -- Constancia * usa 1 VersionPlantilla
    id_version_plantilla  BIGINT       NOT NULL REFERENCES operativo.version_plantilla (id_version),
    fecha_emision         TIMESTAMP    NOT NULL,
    predios_incluidos     VARCHAR(400) NOT NULL,
    rango_fechas          VARCHAR(60)  NOT NULL,
    archivo_pdf           VARCHAR(250) NOT NULL,
    -- Marca "DOCUMENTO DE PRUEBA" cuando se emitió con un servicio simulado (RNF-015).
    es_de_prueba          BOOLEAN      NOT NULL,
    id_trabajador_emisor  BIGINT       REFERENCES seguridad.usuario (id_usuario)
);

-- ===== Registro y traspaso de predio =====

CREATE TABLE operativo.requisito_documental (
    id_requisito     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_tramite     VARCHAR(10)  NOT NULL CHECK (tipo_tramite IN ('REGISTRO', 'TRASPASO')),
    tipo_predio      VARCHAR(10)  NOT NULL CHECK (tipo_predio IN ('URBANO', 'RUSTICO', 'OTRO')),
    nombre_documento VARCHAR(150) NOT NULL,
    obligatorio      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_requisito_documental UNIQUE (tipo_tramite, tipo_predio, nombre_documento)
);

-- Solicitud revisada siempre por una persona de ventanilla (RF-061, RF-056).
CREATE TABLE operativo.solicitud_predio (
    id_solicitud            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_tramite            VARCHAR(10)  NOT NULL CHECK (tipo_tramite IN ('REGISTRO', 'TRASPASO')),
    tipo_predio             VARCHAR(10)  NOT NULL CHECK (tipo_predio IN ('URBANO', 'RUSTICO', 'OTRO')),
    documento_contribuyente VARCHAR(12)  NOT NULL,
    -- SolicitudPredio * registra o traspasa 0..1 Predio (obligatorio en un traspaso).
    codigo_predio           VARCHAR(12),
    estado                  VARCHAR(12)  NOT NULL CHECK (estado IN ('EN_REVISION', 'ACEPTADA', 'RECHAZADA')),
    fecha_envio             TIMESTAMP    NOT NULL,
    firma_electronica       BOOLEAN      NOT NULL DEFAULT FALSE,
    motivo_rechazo          VARCHAR(400),
    id_revisor              BIGINT       REFERENCES seguridad.usuario (id_usuario),
    fecha_revision          TIMESTAMP,
    CONSTRAINT ck_solicitud_predio_traspaso CHECK (tipo_tramite <> 'TRASPASO' OR codigo_predio IS NOT NULL),
    CONSTRAINT ck_solicitud_predio_rechazo CHECK (estado <> 'RECHAZADA' OR motivo_rechazo IS NOT NULL),
    CONSTRAINT ck_solicitud_predio_revision CHECK
        (estado = 'EN_REVISION' OR (id_revisor IS NOT NULL AND fecha_revision IS NOT NULL))
);

CREATE INDEX ix_solicitud_predio_estado ON operativo.solicitud_predio (estado, fecha_envio);
CREATE INDEX ix_solicitud_predio_documento ON operativo.solicitud_predio (documento_contribuyente);

-- SolicitudPredio 1 ◆ 1..* DocumentoAdjunto. Solo PDF, JPG o PNG de hasta 10 MB, cifrados fuera de la raíz web.
CREATE TABLE operativo.documento_adjunto (
    id_adjunto       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_solicitud     BIGINT       NOT NULL REFERENCES operativo.solicitud_predio (id_solicitud) ON DELETE CASCADE,
    -- DocumentoAdjunto * satisface 1 RequisitoDocumental
    id_requisito     BIGINT       NOT NULL REFERENCES operativo.requisito_documental (id_requisito),
    nombre_original  VARCHAR(150) NOT NULL,
    nombre_generado  VARCHAR(64)  NOT NULL UNIQUE,
    tipo_contenido   VARCHAR(5)   NOT NULL CHECK (tipo_contenido IN ('PDF', 'JPG', 'PNG')),
    tamano_bytes     BIGINT       NOT NULL CHECK (tamano_bytes BETWEEN 1 AND 10485760),
    ruta_cifrada     VARCHAR(250) NOT NULL,
    hash_contenido   VARCHAR(64)  NOT NULL
);

-- ===== Buzón y avisos =====

-- Documento en el buzón del contribuyente (RF-030).
CREATE TABLE operativo.documento_buzon (
    id_documento            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_contribuyente VARCHAR(12)  NOT NULL,
    tipo                    VARCHAR(20)  NOT NULL CHECK (tipo IN ('CONSTANCIA', 'ESTADO_CUENTA', 'RESPUESTA_SOLICITUD')),
    titulo                  VARCHAR(150) NOT NULL,
    archivo                 VARCHAR(250),
    fecha_envio             TIMESTAMP    NOT NULL,
    fecha_primera_lectura   TIMESTAMP,
    -- Constancia 1 se deposita 0..1 DocumentoBuzon
    numero_constancia       VARCHAR(20)  UNIQUE REFERENCES operativo.constancia (numero_constancia),
    -- SolicitudPredio 1 respuesta 0..1 DocumentoBuzon
    id_solicitud_predio     BIGINT       UNIQUE REFERENCES operativo.solicitud_predio (id_solicitud),
    CONSTRAINT ck_buzon_lectura CHECK (fecha_primera_lectura IS NULL OR fecha_primera_lectura >= fecha_envio)
);

CREATE INDEX ix_documento_buzon_destinatario ON operativo.documento_buzon (documento_contribuyente, fecha_envio DESC);

-- Aviso de mora temprana o recordatorio de vencimiento por correo (RF-013, RF-022).
CREATE TABLE operativo.aviso_correo (
    id_aviso                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                    VARCHAR(25)  NOT NULL CHECK (tipo IN ('MORA_TEMPRANA', 'RECORDATORIO_VENCIMIENTO')),
    documento_contribuyente VARCHAR(12)  NOT NULL,
    correo_destino          VARCHAR(120) NOT NULL,
    fecha_programada        TIMESTAMP    NOT NULL,
    fecha_envio             TIMESTAMP,
    estado                  VARCHAR(10)  NOT NULL CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'FALLIDO')),
    -- Lote del ETL que lo originó (mora temprana).
    id_lote                 BIGINT       REFERENCES analitica.lote_etl (id_lote),
    -- AvisoCorreo * refiere a 0..1 Obligacion (SAMNET).
    id_obligacion           VARCHAR(20)
);

CREATE INDEX ix_aviso_correo_pendiente ON operativo.aviso_correo (estado, fecha_programada);

-- ===== Copia del estado de cuenta (RNF-002) =====

-- Última copia por contribuyente; se muestra con su fecha de corte cuando SAMNET no responde.
CREATE TABLE operativo.estado_cuenta_copia (
    codigo_contribuyente VARCHAR(10)    PRIMARY KEY,
    fecha_corte          DATE           NOT NULL,
    total_deuda          NUMERIC(14, 2) NOT NULL,
    total_pagado         NUMERIC(14, 2) NOT NULL,
    -- Contribuyente y obligaciones tal como los devolvió SAMNET, en JSON.
    detalle              TEXT           NOT NULL,
    fecha_registro       TIMESTAMP      NOT NULL
);

-- ===== Reportes (Seguimiento institucional) =====

-- Vista personalizada de un reporte del catálogo, guardada por su dueño (RF-008, RF-044).
CREATE TABLE operativo.vista_reporte (
    id_vista           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_reporte       VARCHAR(20)  NOT NULL CHECK (tipo_reporte IN ('MOROSOS', 'PRICOS', 'BUENOS_PAGADORES')),
    id_usuario         BIGINT       NOT NULL REFERENCES seguridad.usuario (id_usuario),
    nombre             VARCHAR(80)  NOT NULL,
    tipo_grafica       VARCHAR(10)  NOT NULL CHECK (tipo_grafica IN ('BARRAS', 'LINEAS', 'CIRCULAR', 'TABLA')),
    filtros            TEXT,
    columnas_visibles  TEXT         NOT NULL,
    orden              VARCHAR(250),
    fecha_creacion     TIMESTAMP    NOT NULL,
    CONSTRAINT uq_vista_reporte_nombre UNIQUE (id_usuario, tipo_reporte, nombre)
);

-- Cada solicitud de generación de un reporte (RF-059).
CREATE TABLE operativo.solicitud_reporte (
    id_solicitud        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_reporte        VARCHAR(20) NOT NULL CHECK (tipo_reporte IN ('MOROSOS', 'PRICOS', 'BUENOS_PAGADORES')),
    id_usuario          BIGINT      NOT NULL REFERENCES seguridad.usuario (id_usuario),
    fecha_hora          TIMESTAMP   NOT NULL,
    filtros_aplicados   TEXT,
    formato_exportacion VARCHAR(10) NOT NULL CHECK (formato_exportacion IN ('NINGUNO', 'EXCEL', 'PDF'))
);

CREATE INDEX ix_solicitud_reporte_tipo_fecha ON operativo.solicitud_reporte (tipo_reporte, fecha_hora);

-- Regla de acceso por rol sobre un reporte o su información; se aplica al ver y al exportar (RF-060).
CREATE TABLE operativo.restriccion_reporte (
    id_restriccion  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol          BIGINT       NOT NULL REFERENCES seguridad.rol (id_rol),
    tipo_reporte    VARCHAR(20)  NOT NULL CHECK (tipo_reporte IN ('MOROSOS', 'PRICOS', 'BUENOS_PAGADORES')),
    dimension       VARCHAR(10)  NOT NULL CHECK (dimension IN ('REPORTE', 'SEGMENTO', 'ZONA')),
    valor_permitido VARCHAR(80),
    permitido       BOOLEAN      NOT NULL,
    CONSTRAINT ck_restriccion_valor CHECK (dimension = 'REPORTE' OR valor_permitido IS NOT NULL)
);

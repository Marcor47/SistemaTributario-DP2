-- Paquete ETL y homologación (RF-038 a RF-041, RF-053, RNF-018). Lo escriben los procesos en Python;
-- la API en Java lo lee para la auditoría de lotes y la bandeja de homologación.

CREATE TABLE analitica.lote_etl (
    id_lote              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Procedimiento de SAMNET de origen (p. ej. ps_etl_cobranza).
    fuente               VARCHAR(80) NOT NULL,
    fecha_corte          DATE        NOT NULL,
    tipo_ejecucion       VARCHAR(10) NOT NULL CHECK (tipo_ejecucion IN ('PROGRAMADA', 'A_DEMANDA')),
    estado               VARCHAR(10) NOT NULL CHECK (estado IN ('EN_CURSO', 'PUBLICADO', 'RECHAZADO')),
    fecha_inicio         TIMESTAMP   NOT NULL,
    fecha_fin            TIMESTAMP,
    registros_leidos     INTEGER     NOT NULL DEFAULT 0 CHECK (registros_leidos >= 0),
    registros_aceptados  INTEGER     NOT NULL DEFAULT 0 CHECK (registros_aceptados >= 0),
    registros_rechazados INTEGER     NOT NULL DEFAULT 0 CHECK (registros_rechazados >= 0),
    CONSTRAINT ck_lote_volumenes CHECK (registros_aceptados + registros_rechazados <= registros_leidos),
    CONSTRAINT ck_lote_fin CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE INDEX ix_lote_etl_estado_fecha ON analitica.lote_etl (estado, fecha_corte DESC);

-- Reglas de calidad basadas en ISO/IEC 25012 (R1 a R5).
CREATE TABLE analitica.regla_calidad (
    id_regla    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(10)  NOT NULL UNIQUE,
    descripcion VARCHAR(250) NOT NULL,
    activa      BOOLEAN      NOT NULL DEFAULT TRUE
);

-- LoteETL 1 ◆ * ResultadoRegla; ReglaCalidad 1 evalúa * ResultadoRegla.
CREATE TABLE analitica.resultado_regla (
    id_resultado        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote             BIGINT      NOT NULL REFERENCES analitica.lote_etl (id_lote) ON DELETE CASCADE,
    id_regla            BIGINT      NOT NULL REFERENCES analitica.regla_calidad (id_regla),
    registros_evaluados INTEGER     NOT NULL CHECK (registros_evaluados >= 0),
    registros_con_error INTEGER     NOT NULL CHECK (registros_con_error >= 0),
    resultado           VARCHAR(10) NOT NULL CHECK (resultado IN ('CUMPLE', 'OBSERVA', 'FALLA')),
    detalle             VARCHAR(400),
    CONSTRAINT uq_resultado_regla_lote UNIQUE (id_lote, id_regla),
    CONSTRAINT ck_resultado_errores CHECK (registros_con_error <= registros_evaluados)
);

-- Registro único de un contribuyente o predio, identificado solo por seudónimo HMAC-SHA-256.
CREATE TABLE maestros.entidad_maestra (
    id_maestro   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_entidad VARCHAR(15) NOT NULL CHECK (tipo_entidad IN ('CONTRIBUYENTE', 'PREDIO')),
    seudonimo    VARCHAR(64) NOT NULL UNIQUE,
    estado       VARCHAR(20) NOT NULL CHECK (estado IN ('ACTIVA', 'PENDIENTE_REVISION'))
);

-- EntidadMaestra 1 ◆ 1..* CorrespondenciaOrigen. Es el dato reidentificable: solo lo leen el servicio
-- de reidentificación y el Administrador (RNF-018).
CREATE TABLE maestros.correspondencia_origen (
    id_correspondencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_maestro         BIGINT      NOT NULL REFERENCES maestros.entidad_maestra (id_maestro) ON DELETE CASCADE,
    sistema_origen     VARCHAR(20) NOT NULL,
    clave_origen       VARCHAR(40) NOT NULL,
    fecha_vinculo      TIMESTAMP   NOT NULL,
    CONSTRAINT uq_correspondencia_origen UNIQUE (sistema_origen, clave_origen)
);

-- Casos que la cascada determinista deja pendientes (bandeja del Responsable de datos, RF-040).
CREATE TABLE analitica.caso_homologacion (
    id_caso              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote              BIGINT       NOT NULL REFERENCES analitica.lote_etl (id_lote),
    -- CasoHomologacion * candidato 0..1 EntidadMaestra
    id_maestro_candidato BIGINT       REFERENCES maestros.entidad_maestra (id_maestro),
    nivel_alcanzado      VARCHAR(30)  NOT NULL CHECK (nivel_alcanzado IN
                             ('N0_CORRESPONDENCIA_PREVIA', 'N1_EXACTA_NORMALIZADA', 'N2_SIMILITUD', 'N3_ALTA_NUEVA')),
    puntaje              NUMERIC(5, 4) CHECK (puntaje BETWEEN 0 AND 1),
    atributos_comparados TEXT         NOT NULL,
    estado               VARCHAR(10)  NOT NULL CHECK (estado IN ('PENDIENTE', 'APROBADO', 'RECHAZADO', 'REASIGNADO'))
);

CREATE INDEX ix_caso_homologacion_estado ON analitica.caso_homologacion (estado);

-- Decisión auditada; no se puede modificar desde la aplicación (RF-053).
CREATE TABLE analitica.decision_homologacion (
    id_decision            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- EntidadMaestra 1 registra * DecisionHomologacion
    id_maestro             BIGINT       NOT NULL REFERENCES maestros.entidad_maestra (id_maestro),
    -- CasoHomologacion 1 se resuelve con 0..1 DecisionHomologacion (nulo si la cascada resolvió sin caso)
    id_caso                BIGINT       UNIQUE REFERENCES analitica.caso_homologacion (id_caso),
    nivel_resolutor        VARCHAR(30)  NOT NULL CHECK (nivel_resolutor IN
                               ('N0_CORRESPONDENCIA_PREVIA', 'N1_EXACTA_NORMALIZADA', 'N2_SIMILITUD', 'N3_ALTA_NUEVA')),
    puntaje                NUMERIC(5, 4) CHECK (puntaje BETWEEN 0 AND 1),
    atributos_coincidentes TEXT,
    tipo_decision          VARCHAR(10)  NOT NULL CHECK (tipo_decision IN ('AUTOMATICA', 'HUMANA')),
    id_usuario             BIGINT       REFERENCES seguridad.usuario (id_usuario),
    fecha_hora             TIMESTAMP    NOT NULL,
    motivo                 VARCHAR(400),
    CONSTRAINT ck_decision_humana CHECK (tipo_decision = 'AUTOMATICA'
                                         OR (id_usuario IS NOT NULL AND motivo IS NOT NULL))
);

CREATE TRIGGER tg_decision_homologacion_inalterable
    BEFORE UPDATE OR DELETE ON analitica.decision_homologacion
    FOR EACH ROW EXECUTE FUNCTION seguridad.fn_registro_inalterable();


-- Paquete Seguridad y administración (RF-047, RF-054, RNF-008, RNF-020 a RNF-024, RNF-028).

CREATE TABLE seguridad.rol (
    id_rol      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(30)  NOT NULL UNIQUE CHECK (nombre IN
                    ('ADMINISTRADOR', 'GERENCIA', 'ANALISTA_RENTAS', 'RESPONSABLE_DATOS', 'VENTANILLA', 'TERMINALISTA')),
    descripcion VARCHAR(250),
    -- Módulos y acciones habilitados, separados por comas (p. ej. REPORTES:CONSULTAR,REPORTES:EXPORTAR).
    permisos    TEXT         NOT NULL DEFAULT ''
);

CREATE TABLE seguridad.usuario (
    id_usuario      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario  VARCHAR(40)  NOT NULL UNIQUE,
    nombre_completo VARCHAR(200) NOT NULL,
    correo          VARCHAR(120) NOT NULL UNIQUE,
    -- Hash adaptativo (bcrypt o Argon2); nunca la clave en texto plano (RNF-020).
    clave_hash      VARCHAR(100) NOT NULL,
    activo          BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMP    NOT NULL
);

-- Usuario * tiene 1..* Rol
CREATE TABLE seguridad.usuario_rol (
    id_usuario BIGINT NOT NULL REFERENCES seguridad.usuario (id_usuario) ON DELETE CASCADE,
    id_rol     BIGINT NOT NULL REFERENCES seguridad.rol (id_rol),
    PRIMARY KEY (id_usuario, id_rol)
);

-- Sesión propia del sistema; para el contribuyente no se guarda ni entrega el token municipal (RNF-028).
CREATE TABLE seguridad.sesion (
    id_sesion           VARCHAR(64)  PRIMARY KEY,
    tipo_sesion         VARCHAR(15)  NOT NULL CHECK (tipo_sesion IN ('INTERNA', 'CONTRIBUYENTE')),
    -- Usuario interno o documento del contribuyente.
    identificador       VARCHAR(40)  NOT NULL,
    id_usuario          BIGINT       REFERENCES seguridad.usuario (id_usuario),
    fecha_inicio        TIMESTAMP    NOT NULL,
    ultima_actividad    TIMESTAMP    NOT NULL,
    minutos_inactividad INTEGER      NOT NULL CHECK (minutos_inactividad > 0),
    ip_origen           VARCHAR(45)  NOT NULL,
    CONSTRAINT ck_sesion_usuario_interno CHECK ((tipo_sesion = 'INTERNA') = (id_usuario IS NOT NULL))
);

CREATE INDEX ix_sesion_ultima_actividad ON seguridad.sesion (ultima_actividad);

-- Historial de auditoría (RNF-008, RNF-033). id_usuario nulo = acción del sistema (ETL, tareas programadas).
CREATE TABLE seguridad.registro_auditoria (
    id_registro    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario     BIGINT       REFERENCES seguridad.usuario (id_usuario),
    accion         VARCHAR(60)  NOT NULL,
    entidad        VARCHAR(120) NOT NULL,
    valor_anterior TEXT,
    valor_nuevo    TEXT,
    fecha_hora     TIMESTAMP    NOT NULL
);

CREATE INDEX ix_registro_auditoria_fecha ON seguridad.registro_auditoria (fecha_hora);

CREATE TRIGGER tg_registro_auditoria_inalterable
    BEFORE UPDATE OR DELETE ON seguridad.registro_auditoria
    FOR EACH ROW EXECUTE FUNCTION seguridad.fn_registro_inalterable();

-- Eventos de seguridad; se conservan al menos 90 días (RNF-024).
CREATE TABLE seguridad.evento_seguridad (
    id_evento   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_evento VARCHAR(25)  NOT NULL CHECK (tipo_evento IN
                    ('LOGIN_OK', 'LOGIN_FALLIDO', 'CAMBIO_ROL', 'ACCESO_DENEGADO', 'ACCESO_DATO_PERSONAL')),
    usuario     VARCHAR(40)  NOT NULL,
    ip_origen   VARCHAR(45)  NOT NULL,
    detalle     VARCHAR(400),
    fecha_hora  TIMESTAMP    NOT NULL
);

CREATE INDEX ix_evento_seguridad_fecha ON seguridad.evento_seguridad (fecha_hora);

-- Parámetros configurables sin modificar código (RF-022, RF-038, RF-052).
CREATE TABLE seguridad.parametro_configuracion (
    clave       VARCHAR(50)  PRIMARY KEY,
    valor       VARCHAR(250) NOT NULL,
    descripcion VARCHAR(250) NOT NULL
);


-- Paquete Inteligencia artificial (RF-023, RF-035, RF-043, RNF-013, RNF-014, RNF-037).
-- Los modelos se ejecutan localmente y solo trabajan con seudónimos.

CREATE TABLE analitica.modelo_ia (
    id_modelo        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(80)  NOT NULL,
    tipo             VARCHAR(20)  NOT NULL CHECK (tipo IN ('SEGMENTACION', 'RESUMEN_EJECUTIVO', 'RIESGO_MORA')),
    version          VARCHAR(20)  NOT NULL,
    -- Hash verificado contra el publicado por la fuente oficial antes de cargar el modelo (RNF-037).
    hash_integridad  VARCHAR(64)  NOT NULL,
    -- Formato que no ejecuta código al cargarse (p. ej. ONNX, GGUF, safetensors).
    formato          VARCHAR(20)  NOT NULL,
    ejecucion_local  BOOLEAN      NOT NULL DEFAULT TRUE CHECK (ejecucion_local),
    fecha_registro   TIMESTAMP    NOT NULL,
    CONSTRAINT uq_modelo_ia_version UNIQUE (nombre, version)
);

-- ModeloIA 1 produce * Segmento; la jefatura lo aprueba antes de publicarlo (RF-043).
CREATE TABLE analitica.segmento (
    id_segmento               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo                 BIGINT       NOT NULL REFERENCES analitica.modelo_ia (id_modelo),
    nombre                    VARCHAR(80)  NOT NULL,
    descripcion               VARCHAR(400),
    tamano                    INTEGER      NOT NULL DEFAULT 0 CHECK (tamano >= 0),
    variables_caracteristicas TEXT         NOT NULL,
    estado                    VARCHAR(10)  NOT NULL CHECK (estado IN ('BORRADOR', 'APROBADO', 'PUBLICADO')),
    id_aprobador              BIGINT       REFERENCES seguridad.usuario (id_usuario),
    fecha_aprobacion          TIMESTAMP,
    CONSTRAINT ck_segmento_aprobacion CHECK
        (estado = 'BORRADOR' OR (id_aprobador IS NOT NULL AND fecha_aprobacion IS NOT NULL))
);

-- Segmento 1 ◆ * AsignacionSegmento; AsignacionSegmento * a 1 DimContribuyente.
CREATE TABLE analitica.asignacion_segmento (
    id_asignacion           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_segmento             BIGINT      NOT NULL REFERENCES analitica.segmento (id_segmento) ON DELETE CASCADE,
    seudonimo_contribuyente VARCHAR(64) NOT NULL REFERENCES analitica.dim_contribuyente (seudonimo_contribuyente),
    fecha_asignacion        TIMESTAMP   NOT NULL,
    segmento_binario_actual VARCHAR(30),
    CONSTRAINT uq_asignacion_segmento UNIQUE (id_segmento, seudonimo_contribuyente)
);

-- ModeloIA 1 genera * ResumenEjecutivo; se basa solo en indicadores calculados (RF-023).
CREATE TABLE analitica.resumen_ejecutivo (
    id_resumen          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo           BIGINT       NOT NULL REFERENCES analitica.modelo_ia (id_modelo),
    periodo             VARCHAR(20)  NOT NULL,
    texto               TEXT         NOT NULL,
    -- Indicadores (y su id de valor) de los que sale cada cifra.
    indicadores_usados  TEXT         NOT NULL,
    estado              VARCHAR(10)  NOT NULL CHECK (estado IN ('GENERADO', 'REVISADO')),
    id_revisor          BIGINT       REFERENCES seguridad.usuario (id_usuario),
    fecha_generacion    TIMESTAMP    NOT NULL,
    CONSTRAINT ck_resumen_300_palabras CHECK
        (array_length(regexp_split_to_array(trim(texto), '\s+'), 1) <= 300),
    CONSTRAINT ck_resumen_revision CHECK (estado = 'GENERADO' OR id_revisor IS NOT NULL)
);

-- ModeloIA 1 calcula * ClasificacionRiesgo (RF-035).
CREATE TABLE analitica.clasificacion_riesgo (
    id_clasificacion        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo               BIGINT        NOT NULL REFERENCES analitica.modelo_ia (id_modelo),
    seudonimo_contribuyente VARCHAR(64)   NOT NULL REFERENCES analitica.dim_contribuyente (seudonimo_contribuyente),
    probabilidad_mora       NUMERIC(5, 4) NOT NULL CHECK (probabilidad_mora BETWEEN 0 AND 1),
    categoria_riesgo        VARCHAR(5)    NOT NULL CHECK (categoria_riesgo IN ('BAJO', 'MEDIO', 'ALTO')),
    fecha_calculo           TIMESTAMP     NOT NULL
);

CREATE INDEX ix_clasificacion_riesgo_contribuyente
    ON analitica.clasificacion_riesgo (seudonimo_contribuyente, fecha_calculo DESC);

-- ModeloIA 1 registra * TrazaIA. Registro inalterable (RNF-014): una revisión humana posterior se
-- registra como una nueva traza.
CREATE TABLE analitica.traza_ia (
    id_traza        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modelo       BIGINT        NOT NULL REFERENCES analitica.modelo_ia (id_modelo),
    entrada         TEXT          NOT NULL,
    salida          TEXT          NOT NULL,
    probabilidad    NUMERIC(5, 4) CHECK (probabilidad BETWEEN 0 AND 1),
    umbral_aplicado NUMERIC(5, 4) CHECK (umbral_aplicado BETWEEN 0 AND 1),
    evidencias      TEXT,
    revision_humana VARCHAR(400),
    fecha_hora      TIMESTAMP     NOT NULL
);

CREATE TRIGGER tg_traza_ia_inalterable
    BEFORE UPDATE OR DELETE ON analitica.traza_ia
    FOR EACH ROW EXECUTE FUNCTION seguridad.fn_registro_inalterable();

CREATE TABLE formulario_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(80) NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    version_numero INTEGER NOT NULL,
    vigente BOOLEAN NOT NULL,
    fecha_publicacion TIMESTAMP WITH TIME ZONE NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL,
    tipo_contenido VARCHAR(120) NOT NULL,
    contenido BYTEA NOT NULL,
    CONSTRAINT uq_formulario_version UNIQUE (codigo, version_numero)
);
CREATE INDEX idx_formulario_vigente ON formulario_version (codigo, vigente);

-- HU009: catálogo de indicadores y metas por periodo
CREATE TABLE analitica.indicador (
    codigo        VARCHAR(40)  PRIMARY KEY,
    nombre        VARCHAR(120) NOT NULL,
    definicion    VARCHAR(400) NOT NULL,
    formula       VARCHAR(250) NOT NULL,
    fuente        VARCHAR(150) NOT NULL,
    unidad_medida VARCHAR(12)  NOT NULL CHECK (unidad_medida IN ('PORCENTAJE', 'SOLES', 'CANTIDAD')),
    periodicidad  VARCHAR(12)  NOT NULL CHECK (periodicidad IN ('MENSUAL', 'TRIMESTRAL', 'ANUAL')),
    sentido       VARCHAR(12)  NOT NULL CHECK (sentido IN ('ASCENDENTE', 'DESCENDENTE')),
    activo        BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE analitica.meta_indicador (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicador_codigo    VARCHAR(40)    NOT NULL REFERENCES analitica.indicador (codigo),
    anio                INTEGER        NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    numero_periodo      INTEGER        NOT NULL CHECK (numero_periodo BETWEEN 1 AND 12),
    valor_meta          NUMERIC(14, 2) NOT NULL CHECK (valor_meta >= 0),
    observacion         VARCHAR(250),
    fecha_registro      TIMESTAMP      NOT NULL,
    fecha_actualizacion TIMESTAMP      NOT NULL,
    CONSTRAINT uq_meta_indicador_periodo UNIQUE (indicador_codigo, anio, numero_periodo)
);


-- HU013: obligaciones emitidas y seguimiento de su cobranza.
-- La tabla obligacion la reutiliza el estado de cuenta (HU004); coordinar cambios con quien la implemente.
CREATE TABLE tributario.obligacion (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contribuyente_codigo VARCHAR(10)    NOT NULL REFERENCES tributario.contribuyente (codigo),
    codigo_predio        VARCHAR(12),
    tributo              VARCHAR(25)    NOT NULL CHECK (tributo IN
                             ('IMPUESTO_PREDIAL', 'LIMPIEZA_PUBLICA', 'PARQUES_JARDINES', 'SEGURIDAD_CIUDADANA')),
    anio                 INTEGER        NOT NULL,
    numero_cuota         INTEGER        NOT NULL CHECK (numero_cuota BETWEEN 1 AND 4),
    fecha_vencimiento    DATE           NOT NULL,
    monto_emitido        NUMERIC(14, 2) NOT NULL CHECK (monto_emitido >= 0),
    monto_pagado         NUMERIC(14, 2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_obligacion_monto_pagado CHECK (monto_pagado BETWEEN 0 AND monto_emitido)
);

CREATE INDEX ix_obligacion_contribuyente_vencimiento
    ON tributario.obligacion (contribuyente_codigo, fecha_vencimiento);

CREATE TABLE tributario.seguimiento_cobranza (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligacion_id        BIGINT       NOT NULL REFERENCES tributario.obligacion (id),
    etapa                VARCHAR(20)  NOT NULL CHECK (etapa IN
                             ('ORDINARIA', 'VALOR_EMITIDO', 'VALOR_NOTIFICADO', 'COACTIVA')),
    fecha_inicio         DATE         NOT NULL,
    documento_referencia VARCHAR(40),
    observacion          VARCHAR(250),
    fecha_registro       TIMESTAMP    NOT NULL,
    CONSTRAINT uq_seguimiento_obligacion_etapa UNIQUE (obligacion_id, etapa)
);

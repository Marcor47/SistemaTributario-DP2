-- Plataforma analítica de Rentas (RF-008, RF-012, RF-044, RNF-003).

-- Fecha y canal del último pago de cada cuota. El ETL los toma de samnet.ps_etl_cobranza; quedan vacíos en una cuota
-- sin pagos o en una carga anterior a estas columnas.
ALTER TABLE analitica.hecho_cobranza
    ADD COLUMN fecha_pago DATE,
    ADD COLUMN canal_pago VARCHAR(10) CHECK (canal_pago IN ('VENTANILLA', 'EN_LINEA'));

-- Vista guardada por su dueño: pestaña, filtros, tipos de gráfico, orden, columnas y comparación fijada.
CREATE TABLE operativo.vista_analitica (
    id_vista            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          BIGINT      NOT NULL REFERENCES seguridad.usuario (id_usuario),
    nombre              VARCHAR(60) NOT NULL,
    estado              TEXT        NOT NULL,
    fecha_actualizacion TIMESTAMP   NOT NULL,
    CONSTRAINT uq_vista_analitica_nombre UNIQUE (id_usuario, nombre)
);
